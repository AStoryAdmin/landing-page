/**
 * Copies the site's header and footer into /samples (premium pass, design
 * spec §1.4). /samples is a static page in public/, outside the React app,
 * so its chrome is a hand copy. This script makes the copy from the built
 * site instead of by hand, so the two can't drift:
 *
 *   npm run build:static && npx vite preview --port 5202 --strictPort
 *   node scripts/samples-chrome.mjs [--base http://localhost:5202] [--check]
 *
 * It loads /compare/ (an ordinary page: Start free, three org rows) at 1440,
 * takes the header and footer markup and every styled-components rule that
 * styles them, renames each root's generated class to .gf-header /
 * .gf-footer, and writes all three (markup, styles, behaviour) into
 * public/samples/index.html between its chrome markers. On /samples the
 * "Sample books" link is the current page.
 *
 * --check writes nothing and exits 1 if the file is out of date.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const file = join(root, 'public', 'samples', 'index.html');
const arg = (name, fallback) => {
  const i = process.argv.indexOf('--' + name);
  return i > -1 ? process.argv[i + 1] : fallback;
};
const base = arg('base', 'http://localhost:5202').replace(/\/$/, '');
const check = process.argv.includes('--check');

const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
await page.goto(base + '/compare/', { waitUntil: 'networkidle' });
await page.waitForTimeout(800);

const got = await page.evaluate(() => {
  const header = document.querySelector('header.gf-header');
  /* The site footer (FooterShell) carries no stable class of its own. */
  const footer = [...document.querySelectorAll('footer')].find((f) => !f.closest('main'));
  /* styled-components v6: "sc-<id> <hash> …user classes". */
  const hashOf = (el) => {
    const c = [...el.classList];
    const i = c.findIndex((x) => x.startsWith('sc-'));
    return i > -1 ? c[i + 1] : null;
  };
  const hashes = new Set();
  for (const rootEl of [header, footer])
    for (const el of [rootEl, ...rootEl.querySelectorAll('*')]) {
      const h = hashOf(el);
      if (h) hashes.add(h);
    }
  const roots = { header: hashOf(header), footer: hashOf(footer) };
  const hit = (sel) =>
    [...hashes].some((h) => new RegExp('\\.' + h + '(?![\\w-])').test(sel));
  const out = [];
  const walk = (rules, into) => {
    for (const r of rules) {
      if (r.selectorText !== undefined) {
        if (hit(r.selectorText)) into.push(r.cssText);
      } else if (r.cssRules && (r.conditionText !== undefined || r.media)) {
        const inner = [];
        walk(r.cssRules, inner);
        if (inner.length) {
          const head = r.cssText.slice(0, r.cssText.indexOf('{')).trim();
          into.push(head + ' {\n' + inner.join('\n') + '\n}');
        }
      }
    }
  };
  for (const s of document.styleSheets) {
    try {
      walk(s.cssRules, out);
    } catch {
      /* cross-origin sheet (fonts): nothing of ours */
    }
  }
  const clean = (el) => {
    const c = el.cloneNode(true);
    c.querySelectorAll('[data-discover]').forEach((x) => x.removeAttribute('data-discover'));
    c.querySelectorAll('[aria-current]').forEach((x) => x.removeAttribute('aria-current'));
    c.classList.remove('is-condensed', 'is-tucked', 'is-open');
    return c.outerHTML;
  };
  return { roots, css: out, header: clean(header), footer: clean(footer) };
});
await browser.close();

const rename = (s) =>
  s
    .replaceAll(new RegExp('\\.' + got.roots.header + '(?![\\w-])', 'g'), '.gf-header')
    .replaceAll(new RegExp('\\.' + got.roots.footer + '(?![\\w-])', 'g'), '.gf-footer');
/* The root elements keep only the stable class. */
const stripRoot = (html, tag, cls) =>
  html.replace(new RegExp('^<' + tag + ' class="[^"]*"'), `<${tag} class="${cls}"`);

let header = stripRoot(got.header, 'header', 'gf-header');
/* On /samples, "Sample books" is the current page. */
header = header.replace('<a href="/samples">', '<a href="/samples" aria-current="page">');
const footer = stripRoot(got.footer, 'footer', 'gf-footer');
const css = rename(got.css.join('\n'));

/*
 * The header's behaviour, as in src/pages/site/Header.tsx (spec §1.1, §1.2):
 * the bar settles past the top and tucks away while scrolling down; the org
 * menu opens on click, or on hover after 120ms where the pointer hovers (a
 * click on a hover-opened panel keeps it open), and Esc, an outside pointer
 * or a link closes it; below 1180px "Menu" opens the sheet (focus trapped,
 * page inert and still), where the org menu is a disclosure in place.
 */
const script = `<script>
/* chrome:script (generated by scripts/samples-chrome.mjs from Header.tsx's behaviour) */
(function(){
  var h=document.querySelector('.gf-header'); if(!h) return;
  var WIDE='(min-width:1180px)', HOVER='(hover: hover) and (pointer: fine)';
  var tog=h.querySelector('.gf-menu-toggle'), orgT=h.querySelector('.org-toggle'),
      panel=h.querySelector('#org-panel'), wrap=h.querySelector('.org-wrap');
  var open=false, org=false, by=null, tucked=false, last=window.scrollY, timer=0;
  var outside=[document.querySelector('main'),document.querySelector('.gf-footer')].filter(Boolean);
  function sync(){
    h.classList.toggle('is-open',open);
    h.classList.toggle('is-tucked',tucked&&!open&&!org);
    h.classList.toggle('is-condensed',window.scrollY>24);
    if(tog){ tog.setAttribute('aria-expanded',String(open)); tog.firstChild.nodeValue=open?'Close ':'Menu '; }
    if(orgT) orgT.setAttribute('aria-expanded',String(org));
    if(panel) panel.hidden=!org;
    document.body.style.overflow=open?'hidden':'';
    if(open) document.body.dataset.navOpen=''; else delete document.body.dataset.navOpen;
    outside.forEach(function(el){ el.inert=open; });
  }
  function shut(){ open=false; org=false; by=null; sync(); }
  var desk=function(){ return !open&&matchMedia(WIDE).matches&&matchMedia(HOVER).matches; };
  if(tog) tog.addEventListener('click',function(){ org=false; by=null; open=!open; sync(); });
  if(orgT) orgT.addEventListener('click',function(){
    clearTimeout(timer);
    if(org&&by==='hover'){ by='click'; return; }
    by=org?null:'click'; org=!org; sync();
  });
  if(wrap){
    wrap.addEventListener('pointerenter',function(){
      if(!desk()) return; clearTimeout(timer); if(org) return;
      timer=setTimeout(function(){ by='hover'; org=true; sync(); },120);
    });
    wrap.addEventListener('pointerleave',function(){
      if(!desk()) return; clearTimeout(timer); if(by!=='hover') return;
      timer=setTimeout(function(){ by=null; org=false; sync(); },200);
    });
    wrap.addEventListener('focusout',function(e){
      if(!open&&!wrap.contains(e.relatedTarget)){ org=false; by=null; sync(); }
    });
  }
  document.addEventListener('keydown',function(e){
    if(e.key==='Escape'){
      if(open){ shut(); tog&&tog.focus(); }
      else if(org){ org=false; by=null; sync(); orgT&&orgT.focus(); }
      return;
    }
    if(e.key==='Tab'&&open){
      var items=[].slice.call(h.querySelectorAll('a,button')).filter(function(x){ return x.getClientRects().length; });
      var first=items[0], lastI=items[items.length-1];
      if(e.shiftKey&&document.activeElement===first){ e.preventDefault(); lastI.focus(); }
      else if(!e.shiftKey&&document.activeElement===lastI){ e.preventDefault(); first.focus(); }
    }
  });
  document.addEventListener('pointerdown',function(e){
    if(org&&!open&&wrap&&!wrap.contains(e.target)){ org=false; by=null; sync(); }
  });
  h.addEventListener('focusin',function(){ if(tucked){ tucked=false; sync(); } });
  window.addEventListener('scroll',function(){
    var y=window.scrollY;
    if(Math.abs(y-last)>6){ tucked=y>last&&y>240; last=y; }
    sync();
  },{passive:true});
  matchMedia(WIDE).addEventListener('change',function(m){ if(m.matches&&open) shut(); });
  h.querySelectorAll('nav a').forEach(function(a){ a.addEventListener('click',shut); });
  sync();
})();
</script>`;

let html = readFileSync(file, 'utf8');
const before = html;
const swap = (re, to, what) => {
  if (!re.test(html)) throw new Error('samples-chrome: could not find the ' + what);
  html = html.replace(re, () => to);
};
swap(/<header class="gf-header"[\s\S]*?<\/header>/, header, 'header');
swap(/<footer class="gf-footer"[\s\S]*?<\/footer>/, footer, 'footer');
swap(
  /\/\* chrome:css:start[\s\S]*?\/\* chrome:css:end \*\//,
  '/* chrome:css:start (generated by scripts/samples-chrome.mjs; do not edit by hand) */\n' +
    css +
    '\n/* chrome:css:end */',
  'chrome:css markers',
);
swap(/<script>\n\/\* chrome:script[\s\S]*?<\/script>/, script, 'chrome:script block');

if (check) {
  console.log(html === before ? 'samples chrome: up to date' : 'samples chrome: OUT OF DATE');
  process.exit(html === before ? 0 : 1);
}
writeFileSync(file, html);
console.log(
  `samples chrome: ${got.css.length} rules, header ${header.length} chars, footer ${footer.length} chars` +
    (html === before ? ' (no change)' : ' (written)'),
);
