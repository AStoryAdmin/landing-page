/**
 * The film's captions and transcript, from one source (design spec §2.4).
 *
 * Reads the timings the v5.6 render actually used,
 * a-story-demo-video/studio/src/v4/vo-words.json (15 lines, v01-v17; NOT
 * brief/vo-lines-v5.3.json, which still has the removed v18), and the music
 * credit from a-story-demo-video/brief/credits.md ("Video description").
 *
 * Writes:
 *   public/film/a-story-film.en.vtt   WebVTT, <v A Story> on A Story's own voice
 *   src/lib/filmTranscript.json       the same lines + the credit, for the page
 *
 * Usage: node scripts/film-captions.mjs [path/to/a-story-demo-video]
 * The demo-video repo defaults to the sibling folder on the Desktop.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const film = resolve(
  process.argv[2] ?? process.env.FILM_REPO ?? resolve(root, "../a-story-demo-video"),
);

const vo = JSON.parse(
  readFileSync(resolve(film, "studio/src/v4/vo-words.json"), "utf8"),
);
const credits = readFileSync(resolve(film, "brief/credits.md"), "utf8");

/* The credit is the fenced block under "## Video description". */
const credit = credits
  .split("## Video description")[1]
  ?.match(/```\s*\n([^`]+?)\n```/)?.[1]
  ?.trim();
if (!credit?.startsWith("Music:")) {
  throw new Error("Music credit not found in brief/credits.md");
}

/* emma is A Story's own voice in the film; ava is the narrator. */
const VOICE = { emma: "A Story" };

const lines = vo.lines.map((l) => ({
  id: l.id,
  speaker: VOICE[l.speaker] ?? null,
  text: l.text.trim(),
  start: Math.round(l.t_in * 1000) / 1000,
  end: Math.round(l.t_out * 1000) / 1000,
}));

if (lines.length !== 15) {
  throw new Error(`Expected 15 lines (v01-v17), found ${lines.length}`);
}
if (lines.some((l) => /coming soon/i.test(l.text))) {
  throw new Error("vo-words.json still contains the removed v18 line");
}

const stamp = (s) => {
  const ms = Math.round(s * 1000);
  const h = String(Math.floor(ms / 3600000)).padStart(2, "0");
  const m = String(Math.floor((ms % 3600000) / 60000)).padStart(2, "0");
  const sec = String(Math.floor((ms % 60000) / 1000)).padStart(2, "0");
  const milli = String(ms % 1000).padStart(3, "0");
  return `${h}:${m}:${sec}.${milli}`;
};

const esc = (t) =>
  t.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

const vtt =
  "WEBVTT\n\n" +
  lines
    .map(
      (l) =>
        `${l.id}\n${stamp(l.start)} --> ${stamp(l.end)}\n` +
        (l.speaker ? `<v ${l.speaker}>${esc(l.text)}` : esc(l.text)),
    )
    .join("\n\n") +
  "\n";

writeFileSync(resolve(root, "public/film/a-story-film.en.vtt"), vtt);
writeFileSync(
  resolve(root, "src/lib/filmTranscript.json"),
  JSON.stringify(
    {
      source:
        "Generated by scripts/film-captions.mjs from a-story-demo-video/studio/src/v4/vo-words.json and brief/credits.md. Do not edit by hand.",
      lines,
      credit,
    },
    null,
    2,
  ) + "\n",
);
console.log(`film-captions: ${lines.length} cues, credit ${credit.length} chars`);
